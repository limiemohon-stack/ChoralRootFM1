# docs/research/harmony_presets.json (the Harmony Engine research pack's 40 phrase examples) -> tests/cr_harmony_pack.h,
# the data cr_harmony_bench's section 6 measures the palette against. Re-run after changing the JSON:
#   python3 tools/harmony_pack_to_c.py docs/research/harmony_presets.json > tests/cr_harmony_pack.h
import json, sys

d = json.load(open(sys.argv[1], encoding="utf-8"))
T = d["chord_templates"]
def c_str(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
def mask(pcs): return "0x%03X" % sum(1 << (p % 12) for p in set(pcs))
out = ["/* SPDX-License-Identifier: GPL-3.0-only",
       " * GENERATED by tools/harmony_pack_to_c.py from docs/research/harmony_presets.json -- do not edit by hand.",
       " * The research pack's %d phrase examples in C, home C: per chord its symbol, root and bass (pitch classes), the" % len(d["phrase_presets"]),
       " * pitch classes it lists (bit pc) and the essential ones (the template's essential intervals, and the bass). */",
       "#define PK_MAXEV 8",
       "typedef struct { const char *sym; unsigned char root, bass; unsigned short pcs, ess; } pk_ev_t;",
       "typedef struct { const char *id, *bank, *name; int n; pk_ev_t ev[PK_MAXEV]; } pk_phrase_t;",
       "static const pk_phrase_t PACK[] = {"]
for p in d["phrase_presets"]:
    evs = []
    assert len(p["events"]) <= 8
    for e in p["events"]:
        r, b = e["root_offset"] % 12, e["bass_offset"] % 12
        ess = [(r + i) % 12 for i in T[e["quality"]]["essential_intervals"]] + [b]
        evs.append("{ %s, %d, %d, %s, %s }" % (c_str(e["example_symbol_C"]), r, b, mask(e["pitch_classes_C"]), mask(ess)))
    out.append("    { %s, %s, %s, %d, {\n        %s } }," % (c_str(p["id"]), c_str(p["bank"]), c_str(p["name"]), len(evs),
               ",\n        ".join(evs)))
out.append("};")
out.append("#define NPACK ((int)(sizeof PACK / sizeof PACK[0]))")
print("\n".join(out))
