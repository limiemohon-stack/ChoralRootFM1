"""Harmony mode's LUVLY view: the figure as points (firmware/src/cr_luvly_fig.h), from the owner's sticker.

    python3 tools/gen_luvly.py STICKER.png [firmware/src/cr_luvly_fig.h]

STICKER.png: the cut-out figure (RGBA, the background transparent; the owner's own artwork, kept out of the repo).
Out: up to N points (CR_LV_N: those left once two on one pixel in one colour are one) (x, y on the 240 x 240 screen; the bone and a 16-colour palette index in one byte), the palette
(RGB565 through CR_RGB, dark colours lifted to a dim grey so the hair's outline shows on the black screen) and the
skeleton's pivots (cr_draw.c cr_p_luvly rotates each point with its bone). The sampling: 30 % of the points on the
head, 50 % over the figure, 20 % on its outline (what reads at this size); seeded, so the same picture gives the same
header. Needs numpy and Pillow (a developer's tool: the build only reads the header)."""
import sys
import numpy as np
from PIL import Image

N = 900
SCALE = 0.175                                   # sticker px -> screen px
BONES = [  # name, start joint, end joint, parent (cr_draw.c LV_POSE follows this order)
    ("torso", "hip", "neck", -1), ("head", "neck", "head", 0), ("bua", "bsh", "bel", 0), ("bfa", "bel", "bha", 2),
    ("fua", "fsh", "fel", 0), ("ffa", "fel", "fha", 4), ("fth", "fhip", "fkn", -1), ("fsn", "fkn", "fan", 6),
    ("fft", "fan", "fft", 7), ("bth", "bhip", "bkn", -1), ("bsn", "bkn", "ban", 9), ("bft", "ban", "bft", 10)]
JOINTS = dict(hip=(880, 580), neck=(1000, 270), head=(1060, 150), bsh=(850, 250), bel=(640, 330), bha=(530, 470),
              fsh=(990, 320), fel=(1160, 440), fha=(1300, 330), fhip=(950, 580), fkn=(1130, 760), fan=(1100, 900),
              fft=(1290, 950), bhip=(800, 620), bkn=(560, 740), ban=(360, 800), bft=(290, 880))


def segd(p, a, b):
    a, b = np.array(a, float), np.array(b, float)
    ab = b - a
    t = np.clip(((p - a) @ ab) / (ab @ ab), 0, 1)
    return np.linalg.norm(p - (a + t[:, None] * ab), axis=1)


def main(src, out):
    rng = np.random.default_rng(7)
    im = np.array(Image.open(src).convert("RGBA"))
    mask = im[..., 3] > 200
    ys, xs = np.nonzero(mask)
    inner = np.roll(mask, 6, 0) & np.roll(mask, -6, 0) & np.roll(mask, 6, 1) & np.roll(mask, -6, 1)
    ey, ex = np.nonzero(mask & ~inner)
    head = mask.copy()
    head[:, :900] = False
    head[330:, :] = False
    hy, hx = np.nonzero(head)
    nh, na = int(N * .30), int(N * .50)
    ih = rng.choice(len(hx), nh, replace=False)
    ia = rng.choice(len(xs), na, replace=False)
    ib = rng.choice(len(ex), N - nh - na, replace=False)
    P = np.concatenate([np.stack([hx[ih], hy[ih]], 1), np.stack([xs[ia], ys[ia]], 1),
                        np.stack([ex[ib], ey[ib]], 1)]).astype(float)
    C = im[P[:, 1].astype(int), P[:, 0].astype(int), :3].astype(float)
    pal = C[rng.choice(len(C), 16, replace=False)]
    for _ in range(16):                         # k-means: 16 colours
        idx = ((C[:, None] - pal[None]) ** 2).sum(2).argmin(1)
        pal = np.array([C[idx == k].mean(0) if (idx == k).any() else pal[k] for k in range(16)])
    idx = ((C[:, None] - pal[None]) ** 2).sum(2).argmin(1)
    for k in range(16):                         # the dark ones lifted: hair, shadows, the shoes' black
        lum = pal[k] @ [.3, .59, .11]
        if lum < 70:
            pal[k] = pal[k] * .4 + np.array([74, 68, 78]) * .6
    bone = np.stack([segd(P, JOINTS[a], JOINTS[b]) for _, a, b, _ in BONES], 1).argmin(1)
    x0, y0 = 230, 34                            # the sticker's box (alpha > 200)
    w, h = (1358 - x0) * SCALE, (992 - y0) * SCALE
    ox, oy = 120 - w / 2 - x0 * SCALE, 206 - h - y0 * SCALE   # centred, its feet at row 206
    def scr(p):
        return np.round(np.asarray(p, float) * SCALE + [ox, oy]).astype(int)
    S = scr(P)
    key = S[:, 1] * 4096 + S[:, 0] * 16 + idx   # two points on one pixel in one colour: one is enough
    _, keep = np.unique(key, return_index=True)
    S, bone, idx = S[keep], bone[keep], idx[keep]
    order = np.lexsort((S[:, 0], S[:, 1]))      # top to bottom: a strip's points together
    S, bone, idx = S[order], bone[order], idx[order]
    n = len(S)
    assert S.min() >= 0 and S.max() < 240
    ctr = S.mean(0)
    L = ["/* Generated by tools/gen_luvly.py from the owner's sticker (the LUVLY figure, the owner's own artwork):",
         " * do not edit. Harmony mode's LUVLY view (cr_draw.c cr_p_luvly). */",
         "#ifndef CR_LUVLY_FIG_H", "#define CR_LUVLY_FIG_H",
         f"#define CR_LV_N {n}u", f"#define CR_LV_NB {len(BONES)}u",
         f"#define CR_LV_CX {int(round(ctr[0]))}", f"#define CR_LV_CY {int(round(ctr[1]))}",
         "/* the points, top to bottom: x, y (screen px), bone << 4 | palette index */",
         "static const uint8_t CR_LV_PT[CR_LV_N][3] = {"]
    row = []
    for (x, y), b, c in zip(S, bone, idx):
        row.append(f"{{{x},{y},{(int(b) << 4) | int(c)}}}")
        if len(row) == 10:
            L.append("    " + ",".join(row) + ",")
            row = []
    if row:
        L.append("    " + ",".join(row) + ",")
    L.append("};")
    L.append("static const uint16_t CR_LV_PAL[16] = {")
    L.append("    " + ", ".join(f"CR_RGB({int(r)}, {int(g)}, {int(b)})" for r, g, b in np.clip(pal, 0, 255)) + "};")
    L.append("/* each bone's pivot (its start joint, screen px) and parent (-1: the root) */")
    L.append("static const struct { uint8_t x, y; int8_t parent; } CR_LV_BONE[CR_LV_NB] = {")
    for name, a, b, par in BONES:
        px, py = scr(JOINTS[a])
        L.append(f"    {{{px}, {py}, {par}}},   /* {name} */")
    L.append("};")
    L.append("#endif")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"{out}: {n} points, bones {np.bincount(bone, minlength=len(BONES)).tolist()}, centre {ctr.round(1)}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "firmware/src/cr_luvly_fig.h")
